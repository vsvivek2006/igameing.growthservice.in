/**
 * Registry Helper Functions
 */
export function getAllIndexablePages(): readonly PageDefinition[] {
  return EXACT_50_PAGES;
}

export function getPageByPath(rawPath: string): PageDefinition | undefined {
  const normalized = rawPath.replace(/\/+$/, '') || '/';
  return EXACT_50_PAGES.find((p) => p.path === normalized);
}

export function getPageById(id: string): PageDefinition | undefined {
  return EXACT_50_PAGES.find((p) => p.id === id);
}

export function getPagesByCategory(category: PageCategory): readonly PageDefinition[] {
  return EXACT_50_PAGES.filter((p) => p.category === category);
}

export function getPagesByType(type: PageType): readonly PageDefinition[] {
  return EXACT_50_PAGES.filter((p) => p.type === type);
}

export function validateRegistryIntegrity(): {
  readonly isValid: boolean;
  readonly count: number;
  readonly errors: readonly string[];
} {
  const errors: string[] = [];

  if (EXACT_50_PAGES.length !== EXPECTED_INDEXABLE_PAGE_COUNT) {
    errors.push(
      `Registry page count mismatch: expected exactly ${EXPECTED_INDEXABLE_PAGE_COUNT}, got ${EXACT_50_PAGES.length}`
    );
  }

  const seenPaths = new Set<string>();
  const seenIds = new Set<string>();
  const seenKeywords = new Set<string>();

  for (const page of EXACT_50_PAGES) {
    if (seenPaths.has(page.path)) {
      errors.push(`Duplicate path in registry: ${page.path}`);
    }
    seenPaths.add(page.path);

    if (seenIds.has(page.id)) {
      errors.push(`Duplicate id in registry: ${page.id}`);
    }
    seenIds.add(page.id);

    const kw = page.primaryKeyword.toLowerCase().trim();
    if (seenKeywords.has(kw)) {
      errors.push(`Duplicate primary keyword detected (cannibalization risk): "${kw}" on ${page.path}`);
    }
    seenKeywords.add(kw);

    if (!page.title || page.title.length < 20) {
      errors.push(`Title too short on ${page.path}`);
    }
    if (!page.description || page.description.length < 50) {
      errors.push(`Description too short on ${page.path}`);
    }
  }

  return {
    isValid: errors.length === 0,
    count: EXACT_50_PAGES.length,
    errors,
  };
}
